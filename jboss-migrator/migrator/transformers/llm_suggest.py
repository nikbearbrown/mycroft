"""Optional: asks Claude for fixes to compile errors left after the mechanical transforms.

Output is a Markdown file of *suggestions* for a human to review. Nothing here edits source.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

log = logging.getLogger(__name__)

_ERROR = re.compile(r"\[ERROR\]\s+(?P<file>[^\s:]+\.java):\[(?P<line>\d+),\d+\]\s+(?P<msg>.+)")
MAX_ERRORS = 40
CONTEXT_LINES = 15

SYSTEM = (
    "You are reviewing a JBoss EAP 7 -> EAP 8 (Jakarta EE 10, Java 17) migration. "
    "Mechanical changes are already applied. For each compile error, propose the smallest "
    "source change that fixes it, as a unified diff, and say if it touches business logic. "
    "If you are not confident, say so instead of guessing."
)


def parse_compile_errors(build_output: str) -> list[dict]:
    seen, errors = set(), []
    for m in _ERROR.finditer(build_output):
        key = (m["file"], m["line"], m["msg"])
        if key not in seen:
            seen.add(key)
            errors.append({"file": m["file"], "line": int(m["line"]), "msg": m["msg"].strip()})
    return errors[:MAX_ERRORS]


def _snippet(path: Path, line: int) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    lo, hi = max(0, line - CONTEXT_LINES), min(len(lines), line + CONTEXT_LINES)
    return "\n".join(f"{i + 1:5d}  {lines[i]}" for i in range(lo, hi))


def suggest(build_output: str, root: Path, model: str, out_file: Path) -> Path | None:
    errors = parse_compile_errors(build_output)
    if not errors:
        return None
    try:
        import anthropic
    except ImportError:
        log.warning("anthropic package not installed; pip install 'jboss-migrator[llm]'")
        return None

    parts = []
    for e in errors:
        path = Path(e["file"]) if Path(e["file"]).is_absolute() else root / e["file"]
        parts.append(f"### {e['file']}:{e['line']}\nError: {e['msg']}\n```java\n"
                     f"{_snippet(path, e['line'])}\n```")

    client = anthropic.Anthropic()
    response = client.beta.messages.create(
        model=model,
        max_tokens=16000,
        thinking={"type": "adaptive"},
        output_config={"effort": "high"},
        # Re-runs on a fallback model if the request is declined by a safety classifier.
        betas=["server-side-fallback-2026-07-01"],
        fallbacks="default",
        system=SYSTEM,
        messages=[{"role": "user", "content": "\n\n".join(parts)}],
    )
    if response.stop_reason == "refusal":
        log.warning("LLM declined to suggest fixes")
        return None
    text = "".join(b.text for b in response.content if b.type == "text")

    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text("# Suggested fixes for remaining compile errors\n\n"
                        "> Generated by an LLM. Review every change; none were applied.\n\n"
                        + text, encoding="utf-8")
    return out_file
