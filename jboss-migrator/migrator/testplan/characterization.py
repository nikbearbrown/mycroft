"""Generates characterization test skeletons for service classes.

A characterization test pins what the code does today so the migrated code can be checked
against it. The generator cannot invent meaningful inputs, so each method gets a disabled test
with a golden-file helper; a developer fills in inputs once, runs it on the baseline to record
the output, and the same test then guards the migrated code.
"""

from __future__ import annotations

from pathlib import Path

from .. import javasrc

_TEMPLATE_JUNIT5 = """package {package};

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Disabled;
import org.junit.jupiter.api.Test;

/**
 * Characterization tests for {name}, generated by jboss-migrator.
 * Fill in inputs, run once on the baseline to record golden output, then remove @Disabled.
 */
class {name}CharacterizationTest {{

    private static final Path GOLDEN = Path.of("src/test/resources/characterization/{name}");

{methods}
    private static void assertMatchesGolden(String key, Object actual) throws Exception {{
        Path file = GOLDEN.resolve(key + ".txt");
        String value = String.valueOf(actual);
        if (!Files.exists(file)) {{
            Files.createDirectories(file.getParent());
            Files.writeString(file, value);
        }}
        assertEquals(Files.readString(file), value, "behaviour of " + key + " changed");
    }}
}}
"""

_METHOD_JUNIT5 = """    @Test
    @Disabled("jboss-migrator: provide inputs for {method}, then record the golden output on the baseline")
    void {method}_matchesBaseline() throws Exception {{
        {name} subject = new {name}(); // TODO: wire dependencies (mocks or test doubles)
        Object result = null;           // TODO: result = subject.{method}(...);
        assertMatchesGolden("{method}", result);
    }}

"""

_TEMPLATE_JUNIT4 = _TEMPLATE_JUNIT5 \
    .replace("import static org.junit.jupiter.api.Assertions.assertEquals;",
             "import static org.junit.Assert.assertEquals;") \
    .replace("import org.junit.jupiter.api.Disabled;\nimport org.junit.jupiter.api.Test;",
             "import org.junit.Ignore;\nimport org.junit.Test;") \
    .replace("class {name}CharacterizationTest", "public class {name}CharacterizationTest") \
    .replace('assertEquals(Files.readString(file), value, "behaviour of " + key + " changed");',
             'assertEquals("behaviour of " + key + " changed", '
             'new String(Files.readAllBytes(file)), value);') \
    .replace("Files.writeString(file, value);", "Files.write(file, value.getBytes());") \
    .replace('Path.of("src/test', 'java.nio.file.Paths.get("src/test')

_METHOD_JUNIT4 = _METHOD_JUNIT5.replace("@Disabled", "@Ignore").replace("    void ", "    public void ")


def generate(root: Path, packages: list[str]) -> list[Path]:
    junit5 = javasrc.uses_junit5(root)
    template, method_tpl = (_TEMPLATE_JUNIT5, _METHOD_JUNIT5) if junit5 else (_TEMPLATE_JUNIT4, _METHOD_JUNIT4)
    written = []
    for pkg in packages:
        pkg_path = pkg.replace(".", "/")
        for src_dir in root.rglob(f"src/main/java/{pkg_path}"):
            for java in sorted(src_dir.glob("*.java")):
                cls = javasrc.parse(java, java.relative_to(root).as_posix())
                if not cls or cls.kind != "class" or not cls.public_methods:
                    continue
                test_rel = src_dir.relative_to(root).as_posix().replace("src/main/java", "src/test/java", 1)
                dest = root / test_rel / f"{cls.name}CharacterizationTest.java"
                if dest.exists():
                    continue
                body = "".join(method_tpl.format(method=m, name=cls.name) for m in cls.public_methods)
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(template.format(package=cls.package, name=cls.name, methods=body),
                                encoding="utf-8")
                written.append(dest)
    return written
